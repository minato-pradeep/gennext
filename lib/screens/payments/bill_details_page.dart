import 'package:flutter/material.dart';
import 'package:provider/provider.dart';
import 'package:printing/printing.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import '../../providers/theme_provider.dart';
import '../../models/payment.dart';
import '../../services/payment_service.dart';
import 'payment_methods_page.dart';
import '../../theme/app_theme.dart';

class BillDetailsPage extends StatefulWidget {
  final UserPaymentSummary userSummary;
  final String userRole;

  const BillDetailsPage({
    super.key,
    required this.userSummary,
    required this.userRole,
  });

  @override
  State<BillDetailsPage> createState() => _BillDetailsPageState();
}

class _BillDetailsPageState extends State<BillDetailsPage> {
  late PaymentService _paymentService;

  @override
  void initState() {
    super.initState();
    _paymentService = PaymentService();
    _paymentService.addListener(_onPaymentUpdate);
  }

  @override
  void dispose() {
    _paymentService.removeListener(_onPaymentUpdate);
    super.dispose();
  }

  void _onPaymentUpdate() {
    if (mounted) {
      setState(() {});
    }
  }

  Future<void> _downloadPDF(Bill bill) async {
    final pdf = pw.Document();

    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(32),
        build: (pw.Context context) => [
          pw.Center(
            child: pw.Column(
              children: [
                pw.SizedBox(height: 20),
                pw.Container(
                  width: 80,
                  height: 80,
                  decoration: const pw.BoxDecoration(
                    color: PdfColors.blue300,
                    shape: pw.BoxShape.circle,
                  ),
                  child: pw.Center(
                    child: pw.Text(
                      '🏠',
                      style: const pw.TextStyle(fontSize: 40),
                    ),
                  ),
                ),
                pw.SizedBox(height: 20),
                pw.Text(
                  'BLUEBUG COMMUNITY',
                  style: pw.TextStyle(
                    fontSize: 24,
                    fontWeight: pw.FontWeight.bold,
                    color: PdfColors.blue900,
                  ),
                ),
                pw.SizedBox(height: 10),
                pw.Text(
                  'Bill Receipt',
                  style: const pw.TextStyle(
                    fontSize: 16,
                    color: PdfColors.grey600,
                  ),
                ),
                pw.SizedBox(height: 30),
                pw.Divider(),
              ],
            ),
          ),
          
          pw.SizedBox(height: 20),
          _buildInfoRow('Bill Type', bill.title),
          _buildInfoRow('Description', bill.description),
          _buildInfoRow('Amount', '₹${bill.amount.toStringAsFixed(0)}'),
          _buildInfoRow('Due Date', bill.dueDate),
          if (bill.status == 'paid') ...[
            _buildInfoRow('Status', 'PAID'),
            _buildInfoRow('Paid Date', bill.paidDate?.substring(0, 10) ?? ''),
            _buildInfoRow('Transaction ID', bill.transactionId ?? ''),
          ] else
            _buildInfoRow('Status', bill.getStatusText().toUpperCase()),
          
          pw.SizedBox(height: 30),
          pw.Divider(),
          
          pw.SizedBox(height: 20),
          pw.Row(
            mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
            children: [
              pw.Text(
                'Generated by BlueBug Community App',
                style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey500),
              ),
              pw.Text(
                'Date: ${DateTime.now().day}/${DateTime.now().month}/${DateTime.now().year}',
                style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey500),
              ),
            ],
          ),
        ],
      ),
    );

    await Printing.sharePdf(
      bytes: await pdf.save(),
      filename: 'Bill_${bill.title}_${widget.userSummary.userName}.pdf',
    );
  }

  pw.Widget _buildInfoRow(String label, String value) {
    return pw.Padding(
      padding: const pw.EdgeInsets.symmetric(vertical: 6),
      child: pw.Row(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          pw.Container(
            width: 100,
            child: pw.Text(
              label,
              style: pw.TextStyle(
                fontSize: 11,
                fontWeight: pw.FontWeight.bold,
                color: PdfColors.grey700,
              ),
            ),
          ),
          pw.Container(
            width: 20,
            child: pw.Text(':', style: const pw.TextStyle(fontSize: 11, color: PdfColors.grey700)),
          ),
          pw.Expanded(
            child: pw.Text(
              value,
              style: const pw.TextStyle(fontSize: 11, color: PdfColors.black),
            ),
          ),
        ],
      ),
    );
  }

  void _navigateToPayment(Bill bill) {
    Navigator.push(
      context,
      MaterialPageRoute(
        builder: (context) => PaymentMethodsPage(
          userId: widget.userSummary.userId,
          bill: bill,
          userName: widget.userSummary.userName,
        ),
      ),
    );
  }

  @override
  Widget build(BuildContext context) {
    final themeProvider = Provider.of<ThemeProvider>(context);
    final isDark = themeProvider.isDarkMode;
    
    final pendingBills = widget.userSummary.bills.where((b) => b.status != 'paid').toList();
    final paidBills = widget.userSummary.bills.where((b) => b.status == 'paid').toList();

    return Scaffold(
      backgroundColor: isDark ? const Color(0xFF121212) : const Color(0xFFF8F9FA),
      appBar: AppBar(
        title: const Text(
          'Bill Details',
          style: TextStyle(fontFamily: 'Arial Narrow', 
            fontSize: 18,
            fontWeight: FontWeight.w600,
            color: Colors.white,
          ),
        ),
        backgroundColor: AppTheme.brandLight(context),
        elevation: 0,
        leading: IconButton(
          icon: const Icon(Icons.arrow_back_ios, color: Colors.white),
          onPressed: () => Navigator.pop(context),
        ),
      ),
      body: DefaultTabController(
        length: 2,
        child: Column(
          children: [
            // User Info
            Container(
              margin: const EdgeInsets.all(16),
              padding: const EdgeInsets.all(16),
              decoration: BoxDecoration(
                color: isDark ? const Color(0xFF1E1E1E) : Colors.white,
                borderRadius: BorderRadius.circular(16),
              ),
              child: Row(
                children: [
                  Container(
                    width: 50,
                    height: 50,
                    decoration: BoxDecoration(
                      color: AppTheme.brandLight(context).withOpacity(0.1),
                      borderRadius: BorderRadius.circular(12),
                    ),
                    child: Icon(Icons.person, color: AppTheme.brandLight(context), size: 28),
                  ),
                  const SizedBox(width: 12),
                  Expanded(
                    child: Column(
                      crossAxisAlignment: CrossAxisAlignment.start,
                      children: [
                        Text(
                          widget.userSummary.userName,
                          style: TextStyle(fontFamily: 'Arial Narrow', 
                            fontSize: 16,
                            fontWeight: FontWeight.w600,
                            color: isDark ? Colors.white : const Color(0xFF212121),
                          ),
                        ),
                        Text(
                          'Apartment: ${widget.userSummary.apartment}',
                          style: TextStyle(fontFamily: 'Arial Narrow', 
                            fontSize: 12,
                            color: isDark ? Colors.white54 : Colors.black45,
                          ),
                        ),
                      ],
                    ),
                  ),
                ],
              ),
            ),
            
            // Tab Bar
            Container(
              margin: const EdgeInsets.symmetric(horizontal: 16),
              decoration: BoxDecoration(
                color: isDark ? const Color(0xFF2A2A2A) : Colors.grey.shade100,
                borderRadius: BorderRadius.circular(12),
              ),
              child: TabBar(
                tabs: [
                  Tab(
                    child: Row(
                      mainAxisAlignment: MainAxisAlignment.center,
                      children: [
                        const Icon(Icons.pending_actions, size: 18),
                        const SizedBox(width: 8),
                        Text('Pending (${pendingBills.length})'),
                      ],
                    ),
                  ),
                  Tab(
                    child: Row(
                      mainAxisAlignment: MainAxisAlignment.center,
                      children: [
                        const Icon(Icons.check_circle, size: 18),
                        const SizedBox(width: 8),
                        Text('Paid (${paidBills.length})'),
                      ],
                    ),
                  ),
                ],
                labelColor: AppTheme.brandLight(context),
                unselectedLabelColor: isDark ? Colors.white54 : Colors.black54,
                indicatorColor: AppTheme.brandLight(context),
              ),
            ),
            
            const SizedBox(height: 16),
            
            // Tab Bar View
            Expanded(
              child: TabBarView(
                children: [
                  // Pending Bills Tab
                  pendingBills.isEmpty
                      ? const Center(
                          child: Column(
                            mainAxisAlignment: MainAxisAlignment.center,
                            children: [
                              Icon(Icons.check_circle_outline, size: 64, color: Color(0xFF4CAF50)),
                              SizedBox(height: 16),
                              Text(
                                'No pending bills!',
                                style: TextStyle(fontFamily: 'Arial Narrow', 
                                  fontSize: 16,
                                  fontWeight: FontWeight.w600,
                                  color: Color(0xFF4CAF50),
                                ),
                              ),
                            ],
                          ),
                        )
                      : ListView.builder(
                          padding: const EdgeInsets.all(16),
                          itemCount: pendingBills.length,
                          itemBuilder: (context, index) {
                            final bill = pendingBills[index];
                            return _buildBillCard(bill, isDark, true);
                          },
                        ),
                  
                  // Paid Bills Tab
                  paidBills.isEmpty
                      ? Center(
                          child: Column(
                            mainAxisAlignment: MainAxisAlignment.center,
                            children: [
                              Icon(Icons.receipt_outlined, size: 64, color: isDark ? Colors.grey.shade700 : Colors.grey.shade300),
                              const SizedBox(height: 16),
                              Text(
                                'No paid bills yet',
                                style: TextStyle(fontFamily: 'Arial Narrow', 
                                  fontSize: 14,
                                  color: isDark ? Colors.white54 : Colors.black45,
                                ),
                              ),
                            ],
                          ),
                        )
                      : ListView.builder(
                          padding: const EdgeInsets.all(16),
                          itemCount: paidBills.length,
                          itemBuilder: (context, index) {
                            final bill = paidBills[index];
                            return _buildBillCard(bill, isDark, false);
                          },
                        ),
                ],
              ),
            ),
          ],
        ),
      ),
    );
  }

  Widget _buildBillCard(Bill bill, bool isDark, bool isPending) {
    return Container(
      margin: const EdgeInsets.only(bottom: 12),
      padding: const EdgeInsets.all(16),
      decoration: BoxDecoration(
        color: isDark ? const Color(0xFF1E1E1E) : Colors.white,
        borderRadius: BorderRadius.circular(16),
        border: Border.all(
          color: bill.getStatusColor().withOpacity(0.3),
          width: 1,
        ),
        boxShadow: [
          BoxShadow(
            color: Colors.black.withOpacity(0.04),
            blurRadius: 8,
            offset: const Offset(0, 2),
          ),
        ],
      ),
      child: Column(
        children: [
          Row(
            children: [
              Container(
                width: 50,
                height: 50,
                decoration: BoxDecoration(
                  color: bill.getStatusColor().withOpacity(0.1),
                  borderRadius: BorderRadius.circular(12),
                ),
                child: Icon(bill.getIcon(), color: bill.getStatusColor(), size: 28),
              ),
              const SizedBox(width: 12),
              Expanded(
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Text(
                      bill.title,
                      style: TextStyle(fontFamily: 'Arial Narrow', 
                        fontSize: 16,
                        fontWeight: FontWeight.w600,
                        color: isDark ? Colors.white : const Color(0xFF212121),
                      ),
                    ),
                    const SizedBox(height: 4),
                    Text(
                      bill.description,
                      style: TextStyle(fontFamily: 'Arial Narrow', 
                        fontSize: 11,
                        color: isDark ? Colors.white54 : Colors.black45,
                      ),
                    ),
                    const SizedBox(height: 6),
                    Row(
                      children: [
                        Icon(Icons.calendar_today, size: 10, color: isDark ? Colors.white54 : Colors.black45),
                        const SizedBox(width: 4),
                        Text(
                          'Due: ${bill.dueDate}',
                          style: TextStyle(fontFamily: 'Arial Narrow', 
                            fontSize: 10,
                            color: isDark ? Colors.white54 : Colors.black45,
                          ),
                        ),
                        const SizedBox(width: 12),
                        Container(
                          padding: const EdgeInsets.symmetric(horizontal: 6, vertical: 2),
                          decoration: BoxDecoration(
                            color: bill.getStatusColor().withOpacity(0.1),
                            borderRadius: BorderRadius.circular(8),
                          ),
                          child: Text(
                            bill.getStatusText(),
                            style: TextStyle(fontFamily: 'Arial Narrow', 
                              fontSize: 9,
                              fontWeight: FontWeight.w600,
                              color: bill.getStatusColor(),
                            ),
                          ),
                        ),
                      ],
                    ),
                    if (bill.status == 'paid' && bill.paidDate != null)
                      Text(
                        'Paid on: ${bill.paidDate!.substring(0, 10)}',
                        style: const TextStyle(fontFamily: 'Arial Narrow', 
                          fontSize: 10,
                          color: Color(0xFF4CAF50),
                        ),
                      ),
                    if (bill.transactionId != null)
                      Text(
                        'Txn ID: ${bill.transactionId}',
                        style: TextStyle(fontFamily: 'Arial Narrow', 
                          fontSize: 9,
                          color: isDark ? Colors.white38 : Colors.black38,
                        ),
                      ),
                  ],
                ),
              ),
              Column(
                crossAxisAlignment: CrossAxisAlignment.end,
                children: [
                  Text(
                    '₹${bill.amount.toStringAsFixed(0)}',
                    style: TextStyle(fontFamily: 'Arial Narrow', 
                      fontSize: 20,
                      fontWeight: FontWeight.w700,
                      color: bill.getStatusColor(),
                    ),
                  ),
                  const SizedBox(height: 8),
                  Row(
                    children: [
                      // Download PDF Button
                      IconButton(
                        onPressed: () => _downloadPDF(bill),
                        icon: const Icon(Icons.picture_as_pdf, color: Color(0xFFE53935), size: 22),
                        tooltip: 'Download PDF',
                      ),
                      // Pay Button (only for pending bills)
                      if (isPending)
                        ElevatedButton.icon(
                          onPressed: () => _navigateToPayment(bill),
                          icon: const Icon(Icons.payment, size: 16),
                          label: const Text('Pay'),
                          style: ElevatedButton.styleFrom(
                            backgroundColor: AppTheme.brandLight(context),
                            padding: const EdgeInsets.symmetric(horizontal: 12, vertical: 8),
                            shape: RoundedRectangleBorder(
                              borderRadius: BorderRadius.circular(20),
                            ),
                          ),
                        ),
                    ],
                  ),
                ],
              ),
            ],
          ),
        ],
      ),
    );
  }
}